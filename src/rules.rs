pub fn meta(id: &str) -> &'static RuleMeta {
    RULES
        .iter()
        .find(|rule| rule.id == id)
        .unwrap_or_else(|| panic!("unknown rule id: {id}"))
}

pub fn make(
    id: &str,
    file: impl Into<String>,
    line: usize,
    evidence: impl Into<String>,
    client: Option<String>,
) -> Finding {
    let meta = meta(id);
    Finding {
        id: meta.id.to_string(),
        severity: meta.severity,
        title: meta.title.to_string(),
        source: meta.layer,
        file: file.into(),
        line: line.max(1),
        client,
        evidence: crate::util::truncate(&evidence.into(), 180),
        owasp: Owasp {
            llm: meta.llm.map(str::to_string),
            mcp: meta.mcp.map(str::to_string),
            agentic: meta.agentic.map(str::to_string),
        },
        fix: Some(meta.fix.to_string()),
        fixable: false,
    }
}
