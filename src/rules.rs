use crate::finding::{Finding, Layer, Owasp, Severity};

pub struct RuleMeta {
    pub id: &'static str,
    pub title: &'static str,
    pub severity: Severity,
    pub layer: Layer,
    pub description: &'static str,
    pub fix: &'static str,
    pub llm: Option<&'static str>,
    pub mcp: Option<&'static str>,
    pub agentic: Option<&'static str>,
}

#[allow(clippy::too_many_arguments)]
const fn rule(
    id: &'static str,
    title: &'static str,
    severity: Severity,
    layer: Layer,
    description: &'static str,
    fix: &'static str,
    llm: Option<&'static str>,
    mcp: Option<&'static str>,
    agentic: Option<&'static str>,
) -> RuleMeta {
    RuleMeta {
        id,
        title,
        severity,
        layer,
        description,
        fix,
        llm,
        mcp,
        agentic,
    }
}

